async function seed() {
  console.log(`Starting to seed ${ALL_STORES.length} stores and ${ALL_BAGS.length} bags...`);

  // 1. Process Stores
  for (const store of ALL_STORES) {
    const storePayload = {
      id: store.id,
      owner_user_id: OWNER_USER_ID,
      name: store.name,
      description: store.description,
      phone: store.phone,
      address: store.address,
      latitude: store.latitude,
      longitude: store.longitude,
      location: `POINT(${store.longitude} ${store.latitude})`,
      logo_url: store.logo_url,
      banner_url: store.banner_url,
      food_categories: store.food_categories,
      open_time: store.open_time,
      close_time: store.close_time,
      is_open: true,
      status: 'active',
      rating: store.rating,
      total_ratings: store.total_ratings,
      commission_rate: 15,
      updated_at: new Date().toISOString(),
    };

    const { error } = await supabaseAdmin.from('stores').upsert(storePayload);
    if (error) {
      console.error(`Failed to upsert store ${store.name}:`, error);
    } else {
      console.log(`✓ Store upserted: ${store.name}`);
    }
  }

  // 2. Process Bags
  for (const bag of ALL_BAGS) {
    const bagPayload = {
      id: bag.id,
      store_id: bag.store_id,
      name: bag.name,
      description: bag.description,
      original_price: bag.original_price,
      discount_price: bag.discount_price,
      category: bag.category,
      image_url: bag.image_url,
      quantity: bag.quantity,
      max_quantity: 3,
      pickup_start: bag.pickup_start,
      pickup_end: bag.pickup_end,
      is_daily: true,
      is_available: true,
      bag_type: 'daily',
      repeat_mode: 'today_only',
      daily_quota: 5,
      status: 'active',
      expires_at: new Date(Date.now() + 90 * 24 * 60 * 60 * 1000).toISOString(),
      updated_at: new Date().toISOString(),
    };

    const { error } = await supabaseAdmin.from('surprise_bags').upsert(bagPayload);
    if (error) {
      console.error(`Failed to upsert bag ${bag.name}:`, error);
    } else {
      console.log(`✓ Bag upserted: ${bag.name}`);
    }
  }

  console.log('Seeding completed successfully!');
}

